def main():
    print("Loading prediction_data.json...")
    with open(PRED_JSON, 'r', encoding='utf-8') as f:
        pred_data = json.load(f)

    print("Loading horse_data.json...")
    with open(HORSE_JSON, 'r', encoding='utf-8') as f:
        horse_data = json.load(f)

    # 1. Update horse_data.json
    h_updated_count = 0
    # Flatten concerns with race 19 prioritized
    flat_concerns = {}
    for r_id in ['24', '23', '22', '21', '20', '19']:
        flat_concerns.update(RACE_CONCERNS.get(r_id, {}))

    for hname, concern in flat_concerns.items():
        if hname in horse_data:
            horse_data[hname]['concerns'] = concern
            h_updated_count += 1
    print(f"Updated {h_updated_count} horses in horse_data.json")

    # 2. Update prediction_data races
    races_updated = 0
    for r_id, r_info in pred_data.get('races', {}).items():
        concerns_map = RACE_CONCERNS.get(str(r_id), flat_concerns)
        # starters
        for s in r_info.get('starters', []):
            hname = s.get('horseName', '')
            if hname in concerns_map:
                s['concerns'] = concerns_map[hname]
            elif hname in flat_concerns:
                s['concerns'] = flat_concerns[hname]
        
        # contenderRanking
        for rk in r_info.get('contenderRanking', []):
            hname = rk.get('horseName', '')
            if hname in concerns_map:
                rk['concerns'] = concerns_map[hname]
            elif hname in flat_concerns:
                rk['concerns'] = flat_concerns[hname]
        
        races_updated += 1

    # 3. Update top-level starters and contenderRanking (activeRaceId = 19)
    active_id = str(pred_data.get('activeRaceId', '19'))
    active_map = RACE_CONCERNS.get(active_id, flat_concerns)

    for s in pred_data.get('starters', []):
        hname = s.get('horseName', '')
        if hname in active_map:
            s['concerns'] = active_map[hname]
        elif hname in flat_concerns:
            s['concerns'] = flat_concerns[hname]

    for rk in pred_data.get('contenderRanking', []):
        hname = rk.get('horseName', '')
        if hname in active_map:
            rk['concerns'] = active_map[hname]
        elif hname in flat_concerns:
            rk['concerns'] = flat_concerns[hname]

    # Save prediction_data.json and prediction_data.js
    with open(PRED_JSON, 'w', encoding='utf-8') as f:
        json.dump(pred_data, f, ensure_ascii=False, indent=2)
    with open(PRED_JS, 'w', encoding='utf-8') as f:
        f.write('export const PREDICTION_DATA = ' + json.dumps(pred_data, ensure_ascii=False, indent=2) + ';\n')
    print("Saved prediction_data.json and prediction_data.js successfully.")

    # Save horse_data.json and horse_data.js
    with open(HORSE_JSON, 'w', encoding='utf-8') as f:
        json.dump(horse_data, f, ensure_ascii=False, indent=2)
    with open(HORSE_JS, 'w', encoding='utf-8') as f:
        f.write('export const HORSE_DATABASE = ' + json.dumps(horse_data, ensure_ascii=False, indent=2) + ';\n')
    print("Saved horse_data.json and horse_data.js successfully.")

if __name__ == '__main__':
    main()
