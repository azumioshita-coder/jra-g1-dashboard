    FINAL_REVIEWS[sid] = race_obj
    print(f"Generated Race {sid} ({race_obj['raceName']}): {len(race_obj['horseReviews'])} runners. Winner: {race_obj['winner']['name']} ({race_obj['winner']['jockey']})")

