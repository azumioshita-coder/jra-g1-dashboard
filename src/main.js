function getWaku(gate, total) {
  if (8 >= total) return gate;
  if (total === 18) {
    if (2 >= gate) return 1;
    if (4 >= gate) return 2;
    if (6 >= gate) return 3;
    if (8 >= gate) return 4;
    if (10 >= gate) return 5;
    if (12 >= gate) return 6;
    if (15 >= gate) return 7;
    return 8;
  }
  if (total === 17) {
    if (2 >= gate) return 1;
    if (4 >= gate) return 2;
    if (6 >= gate) return 3;
    if (8 >= gate) return 4;
    if (10 >= gate) return 5;
    if (12 >= gate) return 6;
    if (14 >= gate) return 7;
    return 8;
  }
  if (total === 16) {
    if (2 >= gate) return 1;
    if (4 >= gate) return 2;
    if (6 >= gate) return 3;
    if (8 >= gate) return 4;
    if (10 >= gate) return 5;
    if (12 >= gate) return 6;
    if (14 >= gate) return 7;
    return 8;
  }
  if (total === 15) {
    if (2 >= gate) return 1;
    if (4 >= gate) return 2;
    if (6 >= gate) return 3;
    if (8 >= gate) return 4;
    if (10 >= gate) return 5;
    if (12 >= gate) return 6;
    if (13 >= gate) return 7;
    return 8;
  }
  return Math.min(8, Math.ceil(gate / 2));
}

function hydrateRaceResults(race) {
  if (race.hydratedResults) return race.hydratedResults;
  const data = RESULTS_DATA[race.id];
  if (!data) return [];
  const results = data.map(mapArrayToResultObj);
  race.hydratedResults = results;
  return results;
}

function mapArrayToResultObj(arr) {
  return {
    rank: arr[0],
    gate: arr[1],
    horseName: arr[2],
    sexAge: arr[3],
    jockeyLoad: arr[4],
    jockey: arr[5],
    time: arr[6],
    margin: arr[7],
    cornerSequence: arr[8],
    last3F: arr[9],
    odds: arr[10],
    popularity: arr[11],
    weight: arr[12],
    weightDiff: arr[13],
    stable: arr[14]
  };
}

function getUniqueGate(usedGates, max) {
  let gate = Math.floor(Math.random() * max) + 1;
  while (usedGates.has(gate)) {
    gate = Math.floor(Math.random() * max) + 1;
  }
  usedGates.add(gate);
  return gate;
}

// ----------------------------------
// 払戻表の完全対応・生成
// ----------------------------------
function hydratePayouts(race) {
  if (race.hydratedPayouts) return race.hydratedPayouts;
  const payouts = PAYOUTS_DATA[race.id];
  if (!payouts) return [];
  race.hydratedPayouts = payouts;
  return payouts;
}

// ----------------------------------
// レース展開（通過順）生成
// ----------------------------------
function getRacePaceSequence(race) {
  const results = hydrateRaceResults(race);
  const corners = [[], [], [], []];
  results.forEach(res => {
    const seq = res.cornerSequence.split('-');
    for (let i = 0; i < 4; i++) {
      corners[i].push({ horse: res.gate, pos: Number(seq[i] || res.rank) });
    }
  });

  const output = [];
  for (let i = 0; i < 4; i++) {
    corners[i].sort((a, b) => a.pos - b.pos);
    const seqStr = corners[i].map(c => c.horse).join('-');
    output.push({
      label: `${i + 1}コーナー`,
      sequence: seqStr
    });
  }
  return output;
}

